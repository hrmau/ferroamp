/// The plain letter behind an accented one, or the character unchanged.
pub fn fold(ch: char) -> char {
    if ch.is_ascii() {
        return ch;
    }
    let mut chars = FOLD.chars();
    while let (Some(accented), Some(base)) = (chars.next(), chars.next()) {
        if accented == ch {
            return base;
        }
    }
    ch
}

fn bitmap(ch: char) -> Option<[u8; 5]> {
    let index = |c: char| (c as usize) - 32;
    if (' '..='~').contains(&ch) {
        return Some(ASCII[index(ch)]);
    }
    let base = fold(ch);
    (base != ch).then(|| ASCII[index(base)])
}

pub fn glyph(ch: char) -> [u8; 5] {
    bitmap(ch).unwrap_or(ASCII[('?' as usize) - 32])
}

/// A stretch of text, ready to draw.
pub enum Piece {
    Glyph([u8; 5]),
    /// Text from outside the bitmap font, drawn by the system.
    Run(Rc<Run>),
}

impl Piece {
    pub fn advance(&self) -> i32 {
        match self {
            Piece::Glyph(_) => ADVANCE,
            Piece::Run(run) => run.width + 1,
        }
    }
}

fn is_combining_mark(ch: char) -> bool {
    matches!(ch, '\u{0300}'..='\u{036F}')
}

/// Splits text into bitmap letters and runs for the system to draw.
pub fn pieces(text: &str) -> Vec<Piece> {
    let chars: Vec<char> = text.chars().collect();
    let mut out = Vec::with_capacity(chars.len());
    let mut i = 0;
    while i < chars.len() {
        let ch = chars[i];
        if ch.is_control() {
            out.push(Piece::Glyph(glyph(' ')));
            i += 1;
        } else if let Some(cols) = bitmap(ch) {
            out.push(Piece::Glyph(cols));
            i += 1;
        } else if is_combining_mark(ch) && i > 0 && bitmap(chars[i - 1]).is_some() {
            // Accents in decomposed names: the letter itself is already drawn.
            i += 1;
        } else {
            let start = i;
            i += 1;
            while let Some(&next) = chars.get(i) {
                if bitmap(next).is_none() && !next.is_control() {
                    i += 1;
                    continue;
                }
                // A sentence stays together, or right-to-left words would be
                // laid out in the wrong order.
                let after_spaces = chars[i..].iter().position(|&c| c != ' ').map(|n| i + n);
                match after_spaces {
                    Some(j) if next == ' ' && bitmap(chars[j]).is_none() => i = j,
                    _ => break,
                }
            }
            let run: String = chars[start..i].iter().collect();
            out.push(Piece::Run(sysfont::run(&run)));
        }
    }
    out
}

/// How far `text` advances, in art pixels.
pub fn width(text: &str) -> i32 {
    if text.is_ascii() {
        text.len() as i32 * ADVANCE
    } else {
        pieces(text).iter().map(Piece::advance).sum()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn polish_letters_fold() {
        assert_eq!(glyph('Ż'), glyph('Z'));
        assert_eq!(glyph('ł'), glyph('l'));
        assert_eq!(glyph('ó'), glyph('o'));
        assert_eq!(glyph('ś'), glyph('s'));
    }

    #[test]
    fn unknown_scripts_show_a_question_mark() {
        assert_eq!(glyph('日'), glyph('?'));
    }

    #[test]
    fn other_scripts_become_runs_and_latin_stays_bitmap() {
        let kinds = |text: &str| -> Vec<bool> {
            pieces(text).iter().map(|p| matches!(p, Piece::Run(_))).collect()
        };
        assert_eq!(kinds("ab"), [false, false]);
        assert_eq!(kinds("\u{17b}"), [false], "accented Latin still folds");
        assert_eq!(kinds("a\u{442}\u{44b}b"), [false, true, false]);
        assert_eq!(kinds("e\u{301}"), [false], "a decomposed accent adds nothing");
        assert_eq!(kinds("\u{5d0} \u{5d1}"), [true], "words of one script stay together");
    }

    #[test]
    fn runs_have_ink_and_width() {
        for text in ["\u{41f}\u{440}\u{438}\u{432}\u{435}\u{442}", "\u{65e5}\u{672c}\u{8a9e}"] {
            let Piece::Run(run) = &pieces(text)[0] else {
                panic!("not a run: {text}");
            };
            assert!(run.width > 10, "{text}: width {}", run.width);
            assert!(run.alpha.iter().any(|&a| a > 128), "{text}: nothing drawn");
        }
    }

    #[test]
    fn fold_table_is_well_formed() {
        assert_eq!(FOLD.chars().count() % 2, 0);
    }
}
